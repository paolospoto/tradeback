export const GB_TERMINATOR = 0x50;

export interface GbCharset {
  decode: Map<number, string>;
  encode: Map<string, number>;
}

function make(entries: readonly (readonly [number, string])[]): GbCharset {
  return { decode: new Map(entries), encode: new Map(entries.map(([b, c]) => [c, b])) };
}

export const GEN1_CHARSET = make(GEN1_ENTRIES);
export const GEN2_CHARSET = make(GEN2_ENTRIES);

/** Decodes a string of `length` bytes, stopping at the terminator. */
export function decodeGbString(set: GbCharset, data: Uint8Array, offset: number, length: number): string {
  let out = "";
  for (let i = 0; i < length; i++) {
    const b = data[offset + i]!;
    if (b === GB_TERMINATOR) break;
    out += set.decode.get(b) ?? "?";
  }
  return out;
}

/**
 * Writes a name into a `length`-byte field: characters, then the terminator repeated up to the end of the
 * field, which is how the real saves store names (checked on the fixtures: "ARTICUNO@@@@" style padding).
 * @throws RangeError when a character has no code or the text does not fit with its terminator.
 */
export function writeGbString(
  set: GbCharset,
  data: Uint8Array,
  offset: number,
  length: number,
  text: string,
): void {
  if (text.length >= length) throw new RangeError(`"${text}" does not fit in ${length - 1} characters`);
  data.fill(GB_TERMINATOR, offset, offset + length);
  for (let i = 0; i < text.length; i++) {
    const code = set.encode.get(text[i]!);
    if (code === undefined) throw new RangeError(`No code for "${text[i]}"`);
    data[offset + i] = code;
  }
}
