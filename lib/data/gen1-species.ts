/** Highest national number in generation I. */
export const MAX_SPECIES_GEN1 = 151;

export interface Gen1Species {
  /** HP, Attack, Defense, Speed, Special. */
  readonly baseStats: readonly [number, number, number, number, number];
  readonly types: readonly [number, number];
  readonly growthRate: GrowthRate;
}

/** National dex number of an internal index, or 0 when the index is not a species. */
export function gen1ToNational(internal: number): number {
  return INTERNAL_TO_NATIONAL[internal] ?? 0;
}

/** Internal index of a national dex number (1-151), or 0. */
export function nationalToGen1(national: number): number {
  return INTERNAL_TO_NATIONAL.indexOf(national, 1) < 0 ? 0 : INTERNAL_TO_NATIONAL.indexOf(national, 1);
}

/** Base data of a national dex number (1-151). */
export function getGen1Species(national: number): Gen1Species {
  const r = ROWS[national - 1];
  if (!r) throw new RangeError(`No generation I species ${national}`);
  return { baseStats: [r[0], r[1], r[2], r[3], r[4]], types: [r[5], r[6]], growthRate: r[7] as GrowthRate };
}
