/**
 * Maps a game language id to the key used in {@link GEN4_TARGET_NAMES}.
 * Korean returns undefined: its names need the Korean glyph table, which v1 does not ship.
 */
export function nameLangOf(language: number): NameLang | undefined {
  switch (language) {
    case LANGUAGE.JA:
      return "ja";
    case LANGUAGE.EN:
      return "en";
    case LANGUAGE.FR:
      return "fr";
    case LANGUAGE.DE:
      return "de";
    case LANGUAGE.IT:
      return "it";
    case LANGUAGE.ES:
      return "es";
    default:
      return undefined;
  }
}
