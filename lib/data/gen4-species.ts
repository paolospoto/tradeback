/**
 * Generation IV (Platinum) species data used by game logic: base stats,
 * abilities, gender ratio and growth rate for all 493 species.
 *
 * Do NOT replace with PokéAPI data: PokéAPI reports the latest generation,
 * which differs for several species.
 *
 * Sources (two independent ones, compared value by value with 0 mismatches):
 * - pret/pokeplatinum decompilation, `res/pokemon/<species>/data.json`
 *   (base_stats, abilities, gender_ratio, exp_rate), commit 2026-11.
 * - PKHeX `PKHeX.Core/Resources/byte/personal/personal_pt` (PersonalInfo4
 *   layout: stats 0x00-0x05, gender 0x10, growth 0x13, abilities 0x16-0x17),
 *   commit 6c95838 (2026-11-16).
 * Ability ids follow the in-game index (pret `generated/abilities.txt`),
 * which matches PokéAPI ability ids 1-123.
 *
 * Generated once by a research script (not part of the build); see
 * docs/formats/gen4.md §7.
 */

/** Stat order used everywhere in this project: HP, Atk, Def, Spe, SpA, SpD (in-game order). */
export type BaseStats = readonly [
  hp: number,
  atk: number,
  def: number,
  spe: number,
  spa: number,
  spd: number,
];

/**
 * Growth rate index (pret `generated/exp_rates.txt`, PKHeX `EXPGrowth`).
 * 0 medium fast, 1 erratic, 2 fluctuating, 3 medium slow, 4 fast, 5 slow.
 */
export type GrowthRate = 0 | 1 | 2 | 3 | 4 | 5;

export interface Gen4Species {
  readonly baseStats: BaseStats;
  /** Ability ids; the second is 0 when the species has a single ability. */
  readonly abilities: readonly [number, number];
  /** 0 = male only, 254 = female only, 255 = genderless, otherwise female threshold. */
  readonly genderRatio: number;
  readonly growthRate: GrowthRate;
}

