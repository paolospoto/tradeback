/**
 * Returns the Generation IV data of a species.
 * @param species National dex number (1-493).
 * @throws RangeError when the species is outside Generation IV.
 */
export function getGen4Species(species: number): Gen4Species {
  const r = ROWS[species - 1];
  if (!r || !Number.isInteger(species))
    throw new RangeError(`Species ${species} is not a Generation IV species`);
  return {
    baseStats: [r[0], r[1], r[2], r[3], r[4], r[5]],
    abilities: [r[6], r[7]],
    genderRatio: r[8],
    growthRate: r[9] as GrowthRate,
  };
}

